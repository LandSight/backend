"""Interpretation report repository port."""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import TYPE_CHECKING


if TYPE_CHECKING:
    from uuid import UUID

    from app.module.interpretation.domain.entity import Interpretation


class InterpretationRepository(ABC):
    """Stores generated interpretation reports, one per analysis."""

    @abstractmethod
    async def get(self, analysis_id: UUID) -> Interpretation | None:
        """Return the stored report of an analysis, or ``None``."""
        raise NotImplementedError

    @abstractmethod
    async def save(self, interpretation: Interpretation) -> Interpretation:
        """Persist the report and return the flushed entity."""
        raise NotImplementedError

    @abstractmethod
    async def update_progress(self, analysis_id: UUID, attempt_id: UUID, done: int, total: int) -> bool:
        """Record the progress of a running attempt.

        Returns ``False`` without writing anything when the report is no longer
        running under ``attempt_id``: it was cancelled, regenerated or deleted.
        """
        raise NotImplementedError

    @abstractmethod
    async def complete_attempt(self, interpretation: Interpretation) -> bool:
        """Store a completed report generated by ``interpretation.attempt_id``.

        The report is written only while it is still running under that
        attempt and is never inserted; returns ``False`` otherwise, so a stale
        attempt cannot overwrite or resurrect the report.
        """
        raise NotImplementedError

    @abstractmethod
    async def delete(self, analysis_id: UUID) -> None:
        """Delete the stored report of an analysis, if any."""
        raise NotImplementedError


__all__ = ("InterpretationRepository",)
