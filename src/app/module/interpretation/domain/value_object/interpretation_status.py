"""Interpretation generation status value object."""

from __future__ import annotations

from enum import StrEnum


class InterpretationStatus(StrEnum):
    """Lifecycle of an interpretation report.

    ``ORDERED``
        The task was queued (or the report is not available yet).
    ``RUNNING``
        The report is being generated by the worker.
    ``COMPLETED``
        The report is generated and stored.
    ``FAILED``
        Generation failed; the report can be regenerated manually.
    """

    ORDERED = "ordered"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


__all__ = ("InterpretationStatus",)
