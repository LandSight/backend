"""Celery-backed interpretation task queue.

Interpretation reports are generated by a dedicated task, one task per
analysis, so the outbox relay never runs LLM calls inline. With a single
worker an earlier report finishes before the next one starts.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, override

from app.module.interpretation.application.port import InterpretationTaskQueue


if TYPE_CHECKING:
    from uuid import UUID

    from celery import Celery


PROCESS_INTERPRETATION_TASK_NAME = "interpretation.process_interpretation"


class CeleryInterpretationTaskQueue(InterpretationTaskQueue):
    """Interpretation task queue backed by Celery + Redis."""

    def __init__(self, celery_app: Celery) -> None:
        self._celery_app = celery_app

    @override
    async def enqueue(self, analysis_id: UUID, current_user_id: UUID) -> None:
        """See :class:`app.module.interpretation.application.port.InterpretationTaskQueue.enqueue`."""
        self._celery_app.send_task(
            PROCESS_INTERPRETATION_TASK_NAME,
            args=[str(analysis_id), str(current_user_id)],
        )


__all__ = ("PROCESS_INTERPRETATION_TASK_NAME", "CeleryInterpretationTaskQueue")
